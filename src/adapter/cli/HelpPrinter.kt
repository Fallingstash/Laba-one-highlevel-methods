package adapter.cli

object HelpPrinter {
    private val TEXT = """
        Использование:
          java -jar app.jar --login <логин> --password <пароль> --action <действие> --resource <путь> --volume <объём>

        Аргументы:
          --login      логин пользователя
          --password   пароль пользователя
          --action     действие: read, write или execute
          --resource   путь до ресурса через точки, например A.B.C
          --volume     запрашиваемый объём (целое неотрицательное число)
          -h, --help   показать эту справку

        Коды ответа:
          0 успех, 1 справка, 2 неверный пароль, 3 неверный логин, 4 неизвестное действие,
          5 нет доступа, 6 ресурс не существует, 7 неверный формат ресурса или объёма,
          8 превышен максимальный объём, 9 ошибка подключения к базе данных, 10 ошибка SQL-запроса

        База данных:
          файл H2, по умолчанию ./data/access (путь без расширения); другой путь задаётся
          переменной окружения ACCESS_DB_PATH. Создать и заполнить базу: scripts/init-db.sh
    """.trimIndent()

    /** Текст справки (отдельно от вывода, чтобы его можно было проверять в тестах). */
    fun text(): String = TEXT
}
